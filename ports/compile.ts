// @env node
import type { BuildMetadata } from './types'
import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { spec, VARIANTS } from '../core/resolve'
import { brandPng } from '../core/scripts/icons'
import { pruneArtifacts } from './artifacts'
import { LIGHTWEIGHT_PORTS, lightweightArchivePath, lightweightPath } from './catalog'
import { COMPILER_VERSION, NEOVIM_SOURCE_REF, NEOVIM_VERSION, PACKAGE_VERSION, SOURCE_REF, VARIANT_LABELS } from './constants'
import { distributionTools, storeFiles } from './distribution'
import { lightweightArtifacts } from './lightweight'
import { neovimData } from './neovim/emit'
import { INTEGRATIONS } from './neovim/integrations'
import { portReadme } from './readme'
import { lua } from './serialize'
import { compileTheme } from './styles'
import { vscodeTheme } from './vscode/emit'
import { zedDistribution } from './zed/distribution'
import { zedFamily } from './zed/emit'
import { zedReadme } from './zed/readme'
import { zip } from './zip'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const outputFlag = process.argv.indexOf('--out')
const output = outputFlag < 0 ? join(root, 'dist/ports') : process.argv[outputFlag + 1]!
if (!output)
  throw new Error('--out needs a path')

function files(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(join(directory, entry.name)) : [join(directory, entry.name)]).sort()
}

function hash(content: string | Buffer): string {
  return createHash('sha256').update(content).digest('hex')
}

const inputs = [...files(join(root, 'ports')), join(root, 'shared/crc32.ts'), ...['color.ts', 'resolve.ts', 'spec.json', 'syntax.ts', 'types.ts', 'scripts/icons.ts'].map(path => join(root, 'core', path))].sort()
const digest = createHash('sha256')
for (const path of inputs) {
  digest.update(`${relative(root, path)}\0`)
  digest.update(readFileSync(path))
  digest.update('\0')
}
const metadata: BuildMetadata = {
  schemaVersion: 1,
  designVersion: spec.version,
  compilerVersion: COMPILER_VERSION,
  inputHash: digest.digest('hex'),
  sourceRepository: 'https://github.com/0froq/lig',
  sourceRef: SOURCE_REF,
  variants: VARIANTS,
  colorPolicy: 'srgb-constant-lh-chroma-reduce',
}
const themes = VARIANTS.map(compileTheme)
const artifacts: Record<string, string | Buffer> = {}
const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`

const mit = readFileSync(join(root, 'LICENSE'), 'utf8')
const zed: Record<string, string | Buffer> = Object.fromEntries(themes.map(theme => [`zed/lig-${theme.variant}.json`, json(zedFamily([theme]))]))
zed['zed/LICENSE'] = mit
zed['zed/lig-zed-all.zip'] = zip(zed)
zed['zed/README.md'] = zedReadme(metadata)
Object.assign(artifacts, zed)
const zedExtension = zedDistribution(themes, metadata)
for (const [path, content] of Object.entries(zedExtension))
  artifacts[`zed-extension/${path}`] = content
artifacts['zed-extension/lig-zed-extension.zip'] = zip(zedExtension)

artifacts['neovim/lua/lig/generated.lua'] = `-- Generated by LiG compiler. Do not edit.\nreturn ${lua(neovimData(themes, { ...metadata, sourceRef: NEOVIM_SOURCE_REF }))}\n`
for (const path of files(join(root, 'ports/neovim/runtime')))
  artifacts[`neovim/${relative(join(root, 'ports/neovim/runtime'), path)}`] = readFileSync(path, 'utf8')
artifacts['neovim/colors/lig.lua'] = 'require("lig").load()\n'
for (const theme of themes)
  artifacts[`neovim/colors/lig-${theme.variant}.lua`] = `require("lig").load({ style = ${lua(theme.variant)} })\n`
artifacts['neovim/lua/lualine/themes/lig.lua'] = 'return require("lig.statusline").lualine()\n'
artifacts['neovim/lua/lightline/colorscheme/lig.lua'] = 'return require("lig.statusline").lightline()\n'
artifacts['neovim/autoload/lightline/colorscheme/lig.vim'] = 'let s:palette = v:lua.require("lightline.colorscheme.lig")\nlet g:lightline#colorscheme#lig#palette = lightline#colorscheme#fill(s:palette)\n'
for (const theme of themes) {
  artifacts[`neovim/lua/lualine/themes/lig-${theme.variant}.lua`] = `return require("lig.statusline").lualine(${lua(theme.variant)})\n`
  const suffix = theme.variant.replaceAll('-', '_')
  artifacts[`neovim/lua/lightline/colorscheme/lig_${suffix}.lua`] = `return require("lig.statusline").lightline(${lua(theme.variant)})\n`
  artifacts[`neovim/autoload/lightline/colorscheme/lig_${suffix}.vim`] = `let s:palette = v:lua.require("lightline.colorscheme.lig_${suffix}")\nlet g:lightline#colorscheme#lig_${suffix}#palette = lightline#colorscheme#fill(s:palette)\n`
}
artifacts['neovim/LICENSE'] = mit
artifacts['neovim/README.md'] = portReadme('neovim', { ...metadata, sourceRef: NEOVIM_SOURCE_REF })
artifacts['neovim/scripts/verify.lua'] = readFileSync(join(root, 'ports/neovim/verify.lua'), 'utf8')
for (const mode of ['light', 'dark']) {
  artifacts[`neovim/colors/lig-${mode}-soft.lua`] = `require("lig").load({ style = "${mode}-paper" })\n`
  artifacts[`neovim/lua/lualine/themes/lig-${mode}-soft.lua`] = `return require("lig.statusline").lualine("${mode}-paper")\n`
}

artifacts['vscode/package.json'] = json({
  name: 'theme-lig',
  displayName: 'LiG Theme for Code',
  publisher: 'froQ',
  version: PACKAGE_VERSION,
  description: 'LiG: a quiet theme with four variants from one palette',
  license: 'MIT',
  icon: 'icon.png',
  engines: { vscode: '^1.107.0' },
  categories: ['Themes'],
  repository: { type: 'git', url: 'https://github.com/0froq/vscode-theme-LiG' },
  contributes: { themes: themes.map(theme => ({ label: VARIANT_LABELS[theme.variant], uiTheme: theme.mode === 'dark' ? 'vs-dark' : 'vs', path: `./themes/lig-${theme.variant}.json` })) },
})
artifacts['vscode/icon.png'] = brandPng()
for (const theme of themes)
  artifacts[`vscode/themes/lig-${theme.variant}.json`] = json(vscodeTheme(theme, VARIANT_LABELS[theme.variant]))
artifacts['vscode/LICENSE.md'] = readFileSync(join(root, 'ports/licenses/MIT-vscode.txt'), 'utf8')
artifacts['vscode/README.md'] = portReadme('vscode', metadata)
artifacts['vscode/.vscodeignore'] = '.git/**\n.github/**\nscripts/**\nassets/**\n.vscode/**\nlig-build.json\nPUBLISHING.md\n'
for (const [path, content] of Object.entries({ ...distributionTools(), ...storeFiles('vscode') }))
  artifacts[`vscode/${path}`] = content
for (const port of ['neovim', 'vscode']) {
  artifacts[`${port}/lig-build.json`] = json({
    ...metadata,
    port,
    packageVersion: port === 'neovim' ? NEOVIM_VERSION : PACKAGE_VERSION,
    distributionRepository: port === 'neovim' ? 'https://github.com/0froq/lig.nvim' : 'https://github.com/0froq/vscode-theme-LiG',
    ...(port === 'neovim' ? { sourceRef: NEOVIM_SOURCE_REF } : {}),
    files: Object.fromEntries(Object.entries(artifacts).filter(([path]) => path.startsWith(`${port}/`)).map(([path, content]) => [path.slice(port.length + 1), hash(content)])),
    coverage: port === 'neovim' ? { integrations: Object.fromEntries(Object.entries(INTEGRATIONS).map(([name, integration]) => [name, { plugin: integration.plugin, groupCount: Object.keys(integration.groups).length }])), statuslines: ['lualine', 'lightline'], runtime: 'native Lua', syntax: ['classic', 'Tree-sitter', 'LSP'] } : { syntax: ['TextMate', 'semantic tokens'], runtime: 'declarative JSON' },
  })
}
const lightweight: Record<string, string | Buffer> = lightweightArtifacts(themes)
const lightweightReadme = readFileSync(join(root, 'ports/lightweight/README.md'), 'utf8')
for (const port of LIGHTWEIGHT_PORTS) {
  const entries = Object.fromEntries(VARIANTS.map((variant) => {
    const path = lightweightPath(port, variant)
    return [path, lightweight[path]!]
  }))
  entries.LICENSE = mit
  // Hatoba needs source integration, so keep those instructions with its download.
  if (port.id === 'hatoba')
    entries['README.md'] = lightweightReadme
  lightweight[lightweightArchivePath(port)] = zip(entries)
}
lightweight.LICENSE = mit
lightweight['README.md'] = lightweightReadme
lightweight['manifest.json'] = json({
  ...metadata,
  sourceRef: SOURCE_REF,
  port: 'lightweight',
  files: Object.fromEntries(Object.entries(lightweight).map(([path, content]) => [path, hash(content)])),
})
for (const [path, content] of Object.entries(lightweight))
  artifacts[`lightweight/${path}`] = content

artifacts['manifest.json'] = json({ ...metadata, files: Object.fromEntries(Object.entries(artifacts).map(([path, content]) => [path, hash(content)])) })
function writeArtifacts(directory: string, artifacts: Record<string, string | Buffer>): void {
  pruneArtifacts(directory, artifacts, check)
  for (const [path, content] of Object.entries(artifacts)) {
    const target = join(directory, path)
    if (check) {
      if (!existsSync(target) || !readFileSync(target).equals(typeof content === 'string' ? Buffer.from(content) : content))
        throw new Error(`Artifact differs: ${target}`)
    }
    else {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, content)
    }
  }
}
writeArtifacts(output, artifacts)
// Custom --out builds remain isolated; the standard build also serves identical bytes.
if (outputFlag < 0) {
  const downloads = { ...lightweight, ...zed }
  delete downloads['manifest.json']
  downloads['manifest.json'] = json({
    ...metadata,
    sourceRef: SOURCE_REF,
    port: 'downloads',
    files: Object.fromEntries(Object.entries(downloads).map(([path, content]) => [path, hash(content)])),
  })
  writeArtifacts(join(root, 'public/ports'), downloads)
}
process.stdout.write(`${check ? 'Checked' : 'Generated'} ${Object.keys(artifacts).length} artifacts; input ${metadata.inputHash}\n`)
